"""Parser for Suno AI metadata text files, style prompts and lyrics."""
from __future__ import annotations

import re
from pathlib import Path
from .models import ParsedSong

STRUCTURE_PATTERN = re.compile(r"\[([A-Za-z0-9_\-/\s]+)\]")
ID_FROM_FILENAME = re.compile(r"\[([a-f0-9\-]{8,})\]")


def extract_style_tags(style: str) -> list[str]:
    """Splits Suno style prompt into normalized descriptive tags."""
    if not style:
        return []
    raw_tags = re.split(r"[,;]+", style)
    tags: list[str] = []
    seen = set()
    for t in raw_tags:
        clean = t.strip()
        # Clean extra whitespace
        clean = re.sub(r"\s+", " ", clean)
        if len(clean) >= 2 and len(clean) <= 60:
            lower = clean.lower()
            if lower not in seen:
                seen.add(lower)
                tags.append(clean)
    return tags


def extract_lyric_sections(lyrics: str) -> list[str]:
    """Extracts Suno structure meta-tags like [Verse 1], [Chorus], [Drop]."""
    if not lyrics:
        return []
    matches = STRUCTURE_PATTERN.findall(lyrics)
    sections: list[str] = []
    seen = set()
    for s in matches:
        clean = s.strip()
        lower = clean.lower()
        if lower not in seen and len(clean) <= 40:
            seen.add(lower)
            sections.append(clean)
    return sections


def parse_suno_txt(content: str, filename: str = "") -> ParsedSong:
    """Parses a Suno AI metadata .txt file generated by Tampermonkey or manual input."""
    song = ParsedSong()

    # Try extracting ID from filename if present: "Song Name [8d1b2c34]_metadata.txt"
    if filename:
        id_match = ID_FROM_FILENAME.search(filename)
        if id_match:
            song.suno_id = id_match.group(1)
        
        # Clean default title from filename
        fn_title = Path(filename).stem
        fn_title = re.sub(r"\s*\[[a-f0-9\-]+\]_metadata$", "", fn_title, flags=re.IGNORECASE)
        fn_title = re.sub(r"_metadata$", "", fn_title, flags=re.IGNORECASE)
        if fn_title:
            song.title = fn_title.replace("_", " ").strip()

    # Normalize line endings
    text = content.replace("\r\n", "\n").replace("\r", "\n")

    # Match sections:
    # 1. Header (lines before first section or between separator bars)
    # 2. [TAM STİL / PROMPT]
    # 3. [ŞARKI SÖZLERİ & META ETİKETLER]

    # Pattern for [TAM STİL / PROMPT]
    style_header_match = re.search(
        r"\[(?:TAM\s+ST[İI]L\s*/\s*PROMPT|ST[İI]L|STYLE|PROMPT)\]",
        text,
        re.IGNORECASE
    )
    # Pattern for [ŞARKI SÖZLERİ & META ETİKETLER]
    lyrics_header_match = re.search(
        r"\[(?:ŞARKI\s+SÖZLER[İI]\s*&?\s*META\s*ET[İI]KETLER|ŞARKI\s+SÖZLER[İI]|LYRICS|SÖZLER)\]",
        text,
        re.IGNORECASE
    )

    header_text = ""
    style_text = ""
    lyrics_text = ""

    if style_header_match and lyrics_header_match:
        if style_header_match.start() < lyrics_header_match.start():
            header_text = text[:style_header_match.start()]
            style_text = text[style_header_match.end():lyrics_header_match.start()]
            lyrics_text = text[lyrics_header_match.end():]
        else:
            header_text = text[:lyrics_header_match.start()]
            lyrics_text = text[lyrics_header_match.end():style_header_match.start()]
            style_text = text[style_header_match.end():]
    elif style_header_match:
        header_text = text[:style_header_match.start()]
        style_text = text[style_header_match.end():]
    elif lyrics_header_match:
        header_text = text[:lyrics_header_match.start()]
        lyrics_text = text[lyrics_header_match.end():]
    else:
        # Fallback if no explicit bracketed section headers
        header_text = text

    # Parse header lines for key-values
    for line in header_text.split("\n"):
        line = line.strip()
        if not line or line.startswith("="):
            continue
        if ":" in line:
            key, val = line.split(":", 1)
            key = key.strip().upper()
            val = val.strip()

            if any(k in key for k in ("ŞARKI ADI", "TITLE", "BAŞLIK")):
                if val:
                    song.title = val
            elif any(k in key for k in ("ŞARKI ID", "SONG ID", "ID")):
                if val:
                    song.suno_id = val
            elif "MODEL" in key:
                if val:
                    song.model = val
            elif any(k in key for k in ("TARİH", "DATE", "ZAMAN")):
                if val:
                    song.created_at = val
            elif any(k in key for k in ("LİNK", "URL", "LINK")):
                if val:
                    song.suno_url = val

    # Clean style and lyrics text
    style_text = re.sub(r"^[\s=]+", "", style_text)
    style_text = re.sub(r"[\s=]+$", "", style_text).strip()

    lyrics_text = re.sub(r"^[\s=]+", "", lyrics_text)
    lyrics_text = re.sub(r"[\s=]+$", "", lyrics_text).strip()

    song.style = style_text
    song.lyrics = lyrics_text

    # Default Suno URL if we have an ID
    if song.suno_id and not song.suno_url:
        song.suno_url = f"https://suno.com/song/{song.suno_id}"

    # Extract tags
    song.tags = extract_style_tags(song.style)
    song.lyric_sections = extract_lyric_sections(song.lyrics)

    return song
